import { writeFileSync } from 'node:fs'
import { DEFAULT_PALETTE, paletteIds, palettes, tokenNames } from './tokens.ts'
import type { PaletteId, Theme } from './tokens.ts'

function block(selector: string, theme: Theme): string {
  const lines = tokenNames.map((name) => `  --app-${name}: ${theme[name]};`)
  return `${selector} {\n${lines.join('\n')}\n}\n`
}

/**
 * Feedway in :root (light) and .dark (the class the colour mode module sets); every other palette
 * behind `data-palette` on <html>, which only redefines the same variables.
 */
export function generateTokensCss(
  source: Record<PaletteId, { light: Theme; dark: Theme }>,
): string {
  const others = paletteIds.filter((id) => id !== DEFAULT_PALETTE)
  return [
    '/* Generated by packages/ui/src/generate-css.ts from tokens.ts. Do not edit. */',
    '',
    block(':root', source[DEFAULT_PALETTE].light),
    block('.dark', source[DEFAULT_PALETTE].dark),
    ...others.flatMap((id) => [
      block(`:root[data-palette="${id}"]:not(.dark)`, source[id].light),
      block(`:root.dark[data-palette="${id}"]`, source[id].dark),
    ]),
  ].join('\n')
}

if (import.meta.main) {
  writeFileSync(new URL('../tokens.css', import.meta.url), generateTokensCss(palettes))
}
